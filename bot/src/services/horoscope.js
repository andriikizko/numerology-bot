export function getDailyHoroscope(pathNumber, date = null) {
  const today = date || new Date();
  const dayOfYear = Math.floor(
    (today - new Date(today.getFullYear(), 0, 0)) / 86400000
  );
  
  const horoscopes = HOROSCOPES[pathNumber] || HOROSCOPES[1];
  const index = dayOfYear % horoscopes.length;
  
  return horoscopes[index];
}

export function formatHoroscope(user, horoscope) {
  const today = new Date();
  const dateStr = today.toLocaleDateString('uk-UA', {
    day: '2-digit',
    month: 'long',
    year: 'numeric'
  });
  
  return `🌟 Гороскоп для ${user.num_name}\n📅 ${dateStr}\n\n"${horoscope}"\n\n_Число долі: ${user.path_number}_`;
}

export function getHoroscopeCount(pathNumber) {
  return HOROSCOPES[pathNumber]?.length || 0;
}
